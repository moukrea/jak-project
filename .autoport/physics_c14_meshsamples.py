UNITS = c6.UNITS
MIN_CLOUD = c6.MIN_CLOUD      # a bone owning fewer dominant vertices carries no surface
PRUNE_MARGIN = 8.0            # a sample within (link radius + this) adds nothing beyond
                              # the existing center+radius test — dropped, and counted.
BSURF_MAX = 12                # surface samples per body bone (farthest-point sampled)
BSURF_MIN_SPREAD = 1.0        # samples collapsing inside this span are one point, not a surface
# STRAY-VERTEX CAP, RELATIVE TO THE BONE'S OWN SPAN.  A `bs` sample is an offset from the bone
# ORIGIN, and a bone's flesh runs the bone's own LENGTH, so a flat absolute bound is a hole
# generator and not an outlier filter: at a flat 2048 units this script dropped 18.53% of all
# body-bone vertices, including 77 of the 109 vertices of mayor-lod0's `chest` (median 2147 on a
# 2558-unit chest->neck span) — i.e. it deleted the very surface the mayor's bow is supposed to
# be measured against.  The bound is therefore the bone's own reach:
#     span = max(|bone - parent|, max over children |bone - child|)
#     cap  = max(BSURF_SPAN_K * span, BSURF_MIN_CAP)
# which still catches real stray weighting (keira-hd lTopStrap2: a 20-vertex cloud sitting 6248
# units out on a 1366-unit bone) because that is many times the bone's own reach.
BSURF_SPAN_K = 2.0
BSURF_MIN_CAP = 512.0         # floor, for tip bones whose span is ~0
CHAR_UNITS = 9420.0           # a jak1 character height — used ONLY as a fallback bound when a
                              # model's own extent is unknown.  It is NOT a validity limit: this
                              # cast contains giants (ogreboss measures 59701 units across and
                              # its Relbow bone alone spans 34651), so the absurdity gate below
                              # is the MODEL'S OWN largest bbox side, never a fixed number.
OUT_MESH = os.path.join(REPO, 'recharged_assets', 'physics_mesh.txt')
OUT_REPORT = os.path.join(REPO, '.autoport', 'reports', 'Grecharged-secondary-motion',
                          'mesh_extents_c14.txt')
