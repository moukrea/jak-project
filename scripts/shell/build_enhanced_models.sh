#!/usr/bin/env bash
# scripts/shell/build_enhanced_models.sh
#
# CONDITIONAL "enhanced HD models" asset-bake for jak1 (autoport Grecharged-hd-models).
#
# ROUND 3 / BRICK 2 REWRITE — SURGICAL merc swap, NOT a level rebake.
# --------------------------------------------------------------------------
# Round 2 baked the enhanced fr3 by RE-DECOMPILING the whole level from the ISO
# (a restricted DGO set) with the HD GLBs dropped into custom_assets/.../merc_replacements/.
# That regenerated EVERY non-character draw of the level, and the restricted rebake does
# NOT reproduce the stock non-character data byte-for-byte (measured: GAME.fr3 diverges at
# a non-merc byte, village1.fr3 flips a texture byte 0x00->0xff) -> the owner's "tout violet"
# (all-magenta) ground. That was a whole-level bake-integrity failure, far bigger than a
# character texture problem.
#
# This rewrite instead loads the STOCK <level>.fr3 and swaps ONLY the named merc model(s)
# in memory via the existing decompiler::replace_model (the tools/hd_merc_swap CLI), then
# re-serializes. Every non-character draw is therefore byte-identical to stock BY
# CONSTRUCTION; an explicit INTEGRITY GATE (hd_merc_swap diff) proves it and refuses to ship
# on any non-character divergence. The stock fr3 in out/jak1/fr3/ are READ ONLY and never
# touched (no backup/restore/trap needed anymore).
#
# The 4 HD character GLBs live in recharged_assets/hd_models/ (regenerated by brick 1 with
# authored PS2 normals + UV-split preserved). They already carry their merc-ctrl <name>-lod0
# identity, so no jak2 ISO re-rip is needed at bake time — the bake depends only on the
# committed GLBs + the stock jak1 fr3.
#
#      eichar-lod0    = Jak    -> COMMON -> GAME.fr3
#      sidekick-lod0  = Daxter -> COMMON -> GAME.fr3
#      sage-lod0      = Samos  -> COMMON -> GAME.fr3   (cycle 3: was village1.fr3)
#      assistant-lod0 = Keira  -> COMMON -> GAME.fr3   (cycle 3: was village1.fr3)
#
# CYCLE-3 FLICKER FIX: keira-hd/samos-hd used to live in village1.fr3, a STREAMED level —
# Loader::get_merc_model returns null the moment village1 leaves memory (level swaps in/around
# cinematics), the companion then submits found=0, the suppression TTL is not re-armed, and the
# actor blacks out for ~2 frames = the owner's cycle-3 NPC flicker (Jak/Daxter, in the always-
# resident GAME.fr3, were immune). ALL FOUR HD models now ride GAME.fr3; village1.fr3 ships a
# stock-identical enhanced copy that OVERWRITES the old overlay (avoids a stale second copy of
# keira-hd/samos-hd on in-place pack updates).
#
# CONDITIONAL: if the staged HD GLBs are absent, this is a NO-OP success (exit 0) — jak1
# then builds STOCK and the in-game toggle stays hidden.
#
# IDEMPOTENT: out/jak1/fr3/enhanced/ is recreated fresh each run; nothing else is mutated.
#
# This script does NOT touch goal_src / game / decompiler source — it only orchestrates the
# offline hd_merc_swap tool and writes the enhanced fr3 overlay.
set -euo pipefail

cd "$(git rev-parse --show-toplevel)"
ROOT="$(pwd)"

log(){ echo "[enhanced-models] $*"; }

STAGE_DIR="recharged_assets/hd_models"
FR3_DIR="out/jak1/fr3"
ENHANCED_OUT="$FR3_DIR/enhanced"
SWAP_BIN="build/tools/hd_merc_swap/hd_merc_swap"

# M4: the canonical HD character set —
#   "<char>|<donor rip GLB>|<target level fr3>|<donor fr3>|<donor model>|<driver stock model>|<driver fr3>".
# 7th field <driver fr3>: fr3 the driver stock model lives in — EMPTY means it is in the target fr3
# (keira/samos are appended to GAME.fr3 but their drivers only exist in village1.fr3).
# Each entry is APPENDED (never re-rig REPLACEd) as merc model <char>-lod0 into the target fr3.
# Cycle 2: the donor rip is STAMPED first (hd_merc_swap stamp) with the donor fr3's exact
# per-draw GS modes / eye slots / effect indices (defect classes C/E/A: see-through fur+jaw+hair
# came from the lossy GLB alphaMode round-trip; white eyes from the dropped eye_id), and the
# append remaps donor eye slots onto the DRIVER's (--eye-from).
# Per-entry IP gate: a missing donor rip is a loud SKIP, not a failure.
#
# CYCLE 4 (blink): each donor fr3 also carries the character's EYELID texture, which NO merc draw
# references (the lid is drawn by EyeRenderer, not by the merc). LID_TEX[<char>] names that donor
# texture; `hd_merc_swap add --port-lid <name>` copies it into the enhanced fr3 under the
# debug_name "<char>-lid" that Merc2 looks up to hand the lid to EyeRenderer.
declare -A LID_TEX=(
  [jak-hd]=jak-orig-eyelid
  [dax-hd]=daxter-eyelid
  [keira-hd]=keira-eyelid
  [samos-hd]=samos-eyelid
  [jak2-hd]=jakb-eyelid
  [jak3-hd]=jakchires-eyelid
  [daxp-hd]=daxter-eyelid
  [keira3-hd]=keira-eyelid
  [ysamos-hd]=samos-eyelid
  [jakm-hd]=jakchires-eyelid
  [jakp-hd]=jakb-eyelid
