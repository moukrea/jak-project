#!/usr/bin/env bash
# scripts/shell/build_enhanced_models.sh
#
# CONDITIONAL "enhanced HD models" asset-bake for jak1 (autoport Grecharged-hd-models).
#
# ROUND 3 / BRICK 2 REWRITE — SURGICAL merc swap, NOT a level rebake.
# --------------------------------------------------------------------------
# Round 2 baked the enhanced fr3 by RE-DECOMPILING the whole level from the ISO
# (a restricted DGO set) with the HD GLBs dropped into custom_assets/.../merc_replacements/.
# That regenerated EVERY non-character draw of the level, and the restricted rebake does
# NOT reproduce the stock non-character data byte-for-byte (measured: GAME.fr3 diverges at
# a non-merc byte, village1.fr3 flips a texture byte 0x00->0xff) -> the owner's "tout violet"
# (all-magenta) ground. That was a whole-level bake-integrity failure, far bigger than a
# character texture problem.
#
# This rewrite instead loads the STOCK <level>.fr3 and swaps ONLY the named merc model(s)
# in memory via the existing decompiler::replace_model (the tools/hd_merc_swap CLI), then
# re-serializes. Every non-character draw is therefore byte-identical to stock BY
# CONSTRUCTION; an explicit INTEGRITY GATE (hd_merc_swap diff) proves it and refuses to ship
# on any non-character divergence. The stock fr3 in out/jak1/fr3/ are READ ONLY and never
# touched (no backup/restore/trap needed anymore).
#
# The 4 HD character GLBs live in recharged_assets/hd_models/ (regenerated by brick 1 with
# authored PS2 normals + UV-split preserved). They already carry their merc-ctrl <name>-lod0
# identity, so no jak2 ISO re-rip is needed at bake time — the bake depends only on the
# committed GLBs + the stock jak1 fr3.
#
#      eichar-lod0    = Jak    -> COMMON   -> GAME.fr3
#      sidekick-lod0  = Daxter -> COMMON   -> GAME.fr3
#      sage-lod0      = Samos  -> village1 -> village1.fr3
#      assistant-lod0 = Keira  -> village1 -> village1.fr3
#
# CONDITIONAL: if the staged HD GLBs are absent, this is a NO-OP success (exit 0) — jak1
# then builds STOCK and the in-game toggle stays hidden.
#
# IDEMPOTENT: out/jak1/fr3/enhanced/ is recreated fresh each run; nothing else is mutated.
#
# This script does NOT touch goal_src / game / decompiler source — it only orchestrates the
# offline hd_merc_swap tool and writes the enhanced fr3 overlay.
set -euo pipefail

cd "$(git rev-parse --show-toplevel)"
ROOT="$(pwd)"

log(){ echo "[enhanced-models] $*"; }

STAGE_DIR="recharged_assets/hd_models"
FR3_DIR="out/jak1/fr3"
ENHANCED_OUT="$FR3_DIR/enhanced"
SWAP_BIN="build/tools/hd_merc_swap/hd_merc_swap"

# The merc-ctrl names whose "Replacing <name> for <lvl>" line MUST appear, and their target fr3.
REPLACE_NAMES=(eichar-lod0 sidekick-lod0 sage-lod0 assistant-lod0)

# The donor dump the HD art is derived from. jak1's 4 HD characters are ripped from the Jak 2
# dump (fr3_to_gltf on decompiler_out/jak2 <- iso_data/jak2). Named here so the IP gate is explicit.
DONOR_DUMP="iso_data/jak2"

# ---------------------------------------------------------------------------
# 0. ARCHITECTURE IP gate (owner 2026-08-02): the HD models derive from the user's Jak 2 dump =
#    Naughty Dog IP. HD may be generated ONLY if that dump is present. Absent -> the feature is
#    unavailable: NO bake, jak1 stays stock (no-op success). build.sh forces --hd-models OFF in the
#    same situation (byte-identical stock build); this is the defensive gate for a direct invocation.
# ---------------------------------------------------------------------------
if [ -z "$(find "$DONOR_DUMP" -maxdepth 2 -type f ! -name '.gitignore' -print -quit 2>/dev/null)" ]; then
  log "donor dump '$DONOR_DUMP' absent — the HD models are ND IP derived from it, so HD is unavailable; skipping enhanced HD bake (jak1 builds stock)"
  exit 0
fi
log "donor dump '$DONOR_DUMP' present — HD generation permitted (ND-derived assets ship EXTERNAL, never in the APK)"

# ---------------------------------------------------------------------------
# 1. ANIM-RETARGET (2026-08-03): prep the HD Jak merc GLB (jak-hd-lod0) from the donor rip, the SAME
#    75-joint prep as the jak-hd art-group (build_hd_jak_artgroup.sh) so the appended merc's bone
#    weights index the companion's skelgroup skeleton. We APPEND this (below) instead of the old
#    re-rig REPLACE of eichar/sidekick/sage/assistant — that REPLACE deformed the characters (the
#    owner's "carnage"). Donor rip absent -> stock (no-op success).
# ---------------------------------------------------------------------------
HD_DONOR_GLB="decompiler_out/jak2/levels/introcst/jakone-highres-lod0.glb"
if [ ! -f "$HD_DONOR_GLB" ]; then
  log "HD donor rip $HD_DONOR_GLB absent — skipping enhanced HD bake (jak1 builds stock, toggle hidden)"
  exit 0
fi
JAKHD_TMP="$(mktemp -d)"; JAKHD_GLB="$JAKHD_TMP/jak-hd-lod0.glb"
trap 'rm -rf "$JAKHD_TMP"' EXIT
python3 scripts/shell/prep_hd_actor_glb.py --in "$HD_DONOR_GLB" --out "$JAKHD_GLB" >/dev/null 2>&1 \
  || { log "prep of jak-hd-lod0.glb from the donor failed"; exit 1; }

# ---------------------------------------------------------------------------
# 2. Require the stock FR3 (read-only source of the swap).
# ---------------------------------------------------------------------------
for f in GAME.fr3 village1.fr3; do
  if [ ! -f "$FR3_DIR/$f" ]; then
    log "stock $FR3_DIR/$f missing — run the normal jak1 decomp first"
    exit 1
  fi
done

# ---------------------------------------------------------------------------
# 3. Ensure the surgical swap tool is built.
# ---------------------------------------------------------------------------
if [ ! -x "$SWAP_BIN" ]; then
  log "building hd_merc_swap tool…"
  cmake --build build --target hd_merc_swap -j"$(nproc)" \
    || { log "failed to build $SWAP_BIN — configure the desktop 'build' tree first"; exit 1; }
fi
[ -x "$SWAP_BIN" ] || { log "$SWAP_BIN missing after build"; exit 1; }

# ---------------------------------------------------------------------------
# 4. Fresh enhanced overlay dir.
# ---------------------------------------------------------------------------
rm -rf "$ENHANCED_OUT"
mkdir -p "$ENHANCED_OUT"

# ---------------------------------------------------------------------------
# 5. Surgical swaps. Each writes a fresh enhanced fr3 from the STOCK fr3, swapping ONLY the
#    named merc model(s). replace_model emits the "Replacing <name> for <lvl>: …" line.
# ---------------------------------------------------------------------------
SWAP_LOG="$(mktemp)"
log "anim-retarget: APPEND jak-hd-lod0 to GAME.fr3 (append-only, NO re-rig replace)…"
"$SWAP_BIN" add "$FR3_DIR/GAME.fr3" "$JAKHD_GLB" "$ENHANCED_OUT/GAME.fr3" 2>&1 | tee -a "$SWAP_LOG"
if ! grep -qE "APPENDED .*jak-hd-lod0" "$SWAP_LOG"; then
  log "APPEND verification FAILED — no 'APPENDED … jak-hd-lod0' line."
  rm -f "$SWAP_LOG"; rm -rf "$ENHANCED_OUT"; exit 1
fi
rm -f "$SWAP_LOG"
log "jak-hd-lod0 merc geometry appended to enhanced/GAME.fr3 (stock characters untouched)."

# ---------------------------------------------------------------------------
# 6. INTEGRITY GATE — every non-character draw in the enhanced fr3 MUST be byte-identical to
#    stock (this is the anti-magenta guarantee). Refuse to ship on any divergence.
# ---------------------------------------------------------------------------
for f in GAME.fr3; do
  if "$SWAP_BIN" diff "$FR3_DIR/$f" "$ENHANCED_OUT/$f" | grep -q "INTEGRITY PASS"; then
    log "integrity gate PASS for $f (non-character draws byte-identical to stock; jak-hd-lod0 appended)."
  else
    log "INTEGRITY GATE FAILED for $f — non-character draws differ from stock. Refusing to ship."
    rm -rf "$ENHANCED_OUT"
    exit 1
  fi
done

# ---------------------------------------------------------------------------
# 7. village2.fr3 — ship a stock-identical copy to OVERWRITE any round-1 stale garbled
#    overlay on an in-place owner update (behaviorally identical to stock either way).
# ---------------------------------------------------------------------------
if [ -f "$FR3_DIR/village2.fr3" ]; then
  cp -p "$FR3_DIR/village2.fr3" "$ENHANCED_OUT/village2.fr3"
  log "stock-identical enhanced/village2.fr3 shipped (kills round-1 stale garbled overlay)"
fi

# ---------------------------------------------------------------------------
# 8. Summary. The stock fr3 in out/jak1/fr3/ were never modified.
# ---------------------------------------------------------------------------
log "DONE — enhanced HD set written to $ENHANCED_OUT/ (stock fr3 untouched):"
for f in GAME.fr3 village1.fr3 village2.fr3; do
  if [ -f "$ENHANCED_OUT/$f" ]; then
    printf '[enhanced-models]     enhanced/%-14s %s bytes\n' "$f" "$(stat -c %s "$ENHANCED_OUT/$f")"
  fi
done
log "enhanced/ is the OPTIONAL overlay shipped for the hd-models toggle; stock stays byte-identical."
